#!/usr/bin/env node
// One-off completeness check (docs/spec-flaws.md F23): does drivstoffapp.no know every fuel station that
// OpenStreetMap knows inside our 3 collection circles, and does it have a price for them?
// Usage: node scripts/osm-coverage.mjs > docs/osm-coverage.md
// Sources: OpenStreetMap via the public Overpass API (ODbL), drivstoffapp.no's open nearby endpoint.
const UA = 'pumpevakt/1.0 (github.com/mariolallana/pumpevakt)';
const CENTRES = [
  { lat: 59.92, lon: 10.56 },
  { lat: 59.9111, lon: 10.7528 },
  { lat: 59.93, lon: 10.95 },
];
const RADIUS_KM = 12;
const MATCH_M = 150;

const toRad = (d) => (d * Math.PI) / 180;
function meters(a, b) {
  const dLat = toRad(b.lat - a.lat);
  const dLon = toRad(b.lon - a.lon);
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(toRad(a.lat)) * Math.cos(toRad(b.lat)) * Math.sin(dLon / 2) ** 2;
  return 2 * 6_371_000 * Math.asin(Math.sqrt(h));
}
const inCircles = (p) => CENTRES.some((c) => meters(c, p) <= RADIUS_KM * 1000);

async function osmStations() {
  const parts = CENTRES.map((c) => `nwr["amenity"="fuel"](around:${RADIUS_KM * 1000},${c.lat},${c.lon});`).join('');
  const q = `[out:json][timeout:60];(${parts});out center tags;`;
  const res = await fetch('https://overpass-api.de/api/interpreter', {
    method: 'POST',
    headers: { 'user-agent': UA, 'content-type': 'application/x-www-form-urlencoded' },
    body: `data=${encodeURIComponent(q)}`,
  });
  if (!res.ok) throw new Error(`Overpass HTTP ${res.status}`);
  const { elements } = await res.json();
  return elements.map((e) => ({
    id: `${e.type}/${e.id}`,
    name: e.tags?.name ?? '',
    brand: e.tags?.brand ?? e.tags?.operator ?? '',
    lat: e.lat ?? e.center.lat,
    lon: e.lon ?? e.center.lon,
    tags: e.tags ?? {},
  }));
}

async function sourceStations(includeNoPrice) {
  const out = new Map();
  const perCentre = [];
  for (const c of CENTRES) {
    const url = `https://backend.drivstoffapp.no/stations/fuel/nearby?lat=${c.lat}&lng=${c.lon}&radius=${RADIUS_KM}&limit=100&include_no_price=${includeNoPrice}`;
    const res = await fetch(url, { headers: { 'user-agent': UA } });
    if (!res.ok) throw new Error(`drivstoffapp HTTP ${res.status}`);
    const list = await res.json();
    perCentre.push(list.length);
    for (const s of list) out.set(s.id, { id: s.id, name: s.name, brand: s.brand, lat: s.location.latitude, lon: s.location.longitude, prices: s.prices });
  }
  return { stations: [...out.values()], perCentre };
}

// Not a public diesel/petrol station: boats only, private, trucks only (cards), abandoned, or gas only.
function notForCars(t) {
  if (t.access === 'private' || t.access === 'no') return 'private';
  if (t['fuel:diesel'] === 'no' && t['fuel:octane_95'] === 'no') return 'no diesel/95';
  if (t.boat === 'yes' || t['waterway'] || /marina|båt/i.test(t.name ?? '')) return 'boats';
  if (t.hgv === 'only' || /truck/i.test(t.name ?? '')) return 'trucks only';
  if (t.disused || t['disused:amenity']) return 'disused';
  const gas = ['cng', 'lpg', 'biogas', 'hydrogen', 'h70', 'h35'].some((f) => t[`fuel:${f}`] === 'yes');
  const liquid = ['diesel', 'octane_95', 'octane_98', 'HVO100'].some((f) => t[`fuel:${f}`] === 'yes');
  if (gas && !liquid) return 'gas only';
  return null;
}

const osm = (await osmStations()).filter(inCircles);
const priced = await sourceStations(false);
const all = await sourceStations(true);
const nearest = (p, list) => list.reduce((best, s) => { const d = meters(p, s); return d < best.d ? { s, d } : best; }, { s: null, d: Infinity });

const rows = osm.map((o) => {
  const p = nearest(o, priced.stations);
  const a = nearest(o, all.stations);
  const status = p.d <= MATCH_M ? 'priced' : a.d <= MATCH_M ? 'listed, no price' : 'not in source';
  return { o, status, excluded: notForCars(o.tags), match: (p.d <= MATCH_M ? p : a).s };
});
const count = (st) => rows.filter((r) => r.status === st && !r.excluded).length;
const relevant = rows.filter((r) => !r.excluded);
const today = new Date().toISOString().slice(0, 10);

console.log(`# OSM coverage check (${today})

Generated by \`node scripts/osm-coverage.mjs\`. Compares every OpenStreetMap \`amenity=fuel\` inside our 3 collection
circles (12 km around Lysaker, Oslo S and Furuset) with what drivstoffapp.no returns. Matched within ${MATCH_M} m.

| | Stations |
|---|---|
| OSM fuel stations in the circles | ${osm.length} |
| …not diesel/petrol for cars (gas only, boats, private, trucks only, disused) | ${osm.length - relevant.length} |
| **Public diesel/petrol stations** | **${relevant.length}** |
| Priced in drivstoffapp.no (what Pumpevakt shows) | ${count('priced')} (${Math.round((100 * count('priced')) / relevant.length)} %) |
| Listed in drivstoffapp.no but no price | ${count('listed, no price')} |
| Not in drivstoffapp.no at all | ${count('not in source')} |

drivstoffapp.no returned ${priced.perCentre.join(' / ')} priced and ${all.perCentre.join(' / ')} total stations per circle
(the API caps at 100${[...priced.perCentre, ...all.perCentre].some((n) => n >= 100) ? ': **a circle hit the cap, so results there are truncated**' : '; no circle hit it'}).

## Public diesel/petrol stations without a price in Pumpevakt

| OSM name | Brand | Status | Where |
|---|---|---|---|
${relevant
  .filter((r) => r.status !== 'priced')
  .sort((a, b) => a.status.localeCompare(b.status) || a.o.name.localeCompare(b.o.name))
  .map((r) => `| ${r.o.name || '(no name)'} | ${r.o.brand || ''} | ${r.status} | [${r.o.lat.toFixed(4)}, ${r.o.lon.toFixed(4)}](https://www.openstreetmap.org/${r.o.id}) |`)
  .join('\n')}

## Excluded (not diesel/petrol for cars)

| OSM name | Reason | In drivstoffapp.no |
|---|---|---|
${rows
  .filter((r) => r.excluded)
  .sort((a, b) => a.excluded.localeCompare(b.excluded) || a.o.name.localeCompare(b.o.name))
  .map((r) => `| ${r.o.name || '(no name)'} | ${r.excluded} | ${r.status} |`)
  .join('\n')}

OSM data © OpenStreetMap contributors, ODbL.`);
